//! A hash reads its message 64 bytes at a time and carries eight words of
//! state, so what it holds should be a property of the algorithm rather than
//! of the message. `sha256/hex` holds the message instead: doubling the input
//! doubles the peak arena, exactly, and the constant is about seven thousand
//! bytes of live memory for every byte hashed.
//!
//! This asserts what the hash DOES, not what it should do. The numbers are
//! deterministic to the byte — three runs of each size agree — so they are
//! pinned rather than bounded, and a change that makes the hash stream will
//! turn this red. That is the point: the entry that stops matching is the
//! reminder, the same contract tests/golden/wasm_gaps.txt keeps.
//!
//! WHY IT MATTERS AWAY FROM THE TEST. `scripts/fingerprint` digests the site's
//! assets, and docs/kanso.wasm is 1,604,098 bytes. At this rate that is roughly
//! eleven gigabytes of live arena for one file; measured, the kernel's own
//! out-of-memory report for that run read anon-rss 13,954,684 kB. The
//! asset-digests job passes on CI, so the runner has headroom this container
//! did not — but the headroom shrinks by about seven kilobytes for every byte
//! added to the blob, and nothing in the tree was watching that.
//!
//! The in-place append is NOT the cause and was the first guess: at 25,000
//! bytes the run reads push_mut_fast=1,904,531 against push_mut_slow=125,541,
//! so 93.8% of appends already take the fast path. What the counters do say is
//! that nothing is ever reclaimed — cohort_frees=0, and alloc_bytes lands
//! within half a per cent of arena_peak_bytes, which is one fact said twice:
//! every byte allocated is still live when the program ends. 89% of that peak
//! is buffer (sh_buf=220,980,512 of 247,463,936).

use std::process::Command;

/// Peak arena bytes for hashing `n` generated bytes.
fn peak_bytes(n: u64) -> u64 {
    let dir = std::env::temp_dir().join(format!("kanso-sha256-peak-{n}"));
    std::fs::create_dir_all(&dir).expect("a directory to run in");
    // The message is built rather than read so the spec needs no fixture, and
    // `% 251` keeps it from being a run of one repeated byte.
    let program = format!(
        "import \"std/sha256\"\n\n\
         fn bytes 0 acc\n  acc\n\n\
         fn bytes n acc\n  bytes (n - 1) (push acc (n % 251))\n\n\
         print (sha256/hex (bytes {n} []))\n"
    );
    std::fs::write(dir.join("run.kso"), program).expect("the program writes");

    let done = Command::new(env!("CARGO_BIN_EXE_kanso"))
        .arg("play")
        .arg("run.kso")
        .env("KANSO_COUNTERS", "1")
        .current_dir(&dir)
        .output()
        .expect("kanso runs");
    let said = String::from_utf8_lossy(&done.stderr).into_owned();
    let _ = std::fs::remove_dir_all(&dir);

    said.lines()
        .find_map(|l| l.trim().strip_prefix("arena_peak_bytes=")?.parse().ok())
        .unwrap_or_else(|| panic!("no arena_peak_bytes in:\n{said}"))
}

/// Twice the message, more than twice the arena. A streaming hash would read
/// the same number at every size, and when one does this assertion is the
/// thing to delete.
///
/// Until 2026-09-07 the pins were 7,340,032 at 1,024 bytes and 14,680,064 at
/// 2,048, exactly linear, and seven kilobytes of arena a message byte. That
/// was the round table: sha256's sixty-four constants were joined from eleven
/// literal lists at every `rounds[at]`, sixty-four times a block, and the
/// garbage of rebuilding them was the peak. Every constant is built once now,
/// and what is left is the hash's own retention -- the schedule and the
/// working words of every block, still held to the end -- which reads
/// 1,048,576 at both old sizes because that is one arena block, the floor
/// nothing smaller can show. The sizes below sit above the floor. The peak
/// is no longer an exact doubling because the arena grows by whole blocks,
/// but it grows with the message, which is the defect this spec is about.
///
/// Re-pinned 2026-09-15 when the empty list literal opened with room for
/// four (the `empty_room` row). The message accumulator is built by pushing
/// into `[]`, and where its buffer lands moved with the literal's shape: at
/// 65,536 bytes the arena peak rose two blocks, 17,825,808 -> 19,922,976,
/// while the permanent peak fell 2,621,472 -> 1,310,752; at 131,072 the
/// arena fell eight blocks, 40,894,496 -> 32,505,888, and the permanent peak
/// rose 2,621,472 -> 5,242,912. Summed, the smaller message holds 786,448
/// bytes more and the larger 5,767,168 less. Both are placement, and both
/// are still a peak that grows with the message.
///
/// RE-PINNED AGAIN 2026-09-19, and this time a third of the retention went.
/// `beat_loops` used to strip the carry from every group whose file begins
/// `std/` or `lib/`, which took `sha256/blocked` and `sha256/digested` out of
/// the carry tier and left every block's schedule and working words live to
/// the end of the hash. The rule reads the loop's own shape now -- an imported
/// group keeps a carry of at most one position -- and those two keep theirs.
/// Across the range:
///
///        bytes      before        after
///       16,384   6,291,472    3,145,744
///       32,768   9,437,200    3,145,744
///       65,536  19,922,976    7,340,064
///      131,072  32,505,888    7,340,064
///      262,144  75,497,520   24,117,296
///
/// Two to four times less, and the doubling from 65,536 to 131,072 now costs
/// nothing at all. THE DEFECT IS NOT GONE: 262,144 still reads three times
/// 131,072, and per message byte the hash still holds 92 bytes where it held
/// 288. The header above projects the site's 1,604,098-byte wasm blob at
/// roughly eleven gigabytes of live arena; that projection is nearer three and
/// a half now, which is an improvement and not a fix.
#[test]
fn a_hash_holds_every_block_it_has_read() {
    let short = peak_bytes(65_536);
    let long = peak_bytes(131_072);
    let longer = peak_bytes(262_144);

    assert_eq!(short, 7_340_064, "the 65,536-byte peak moved");
    assert_eq!(long, 7_340_064, "the 131,072-byte peak moved");
    assert_eq!(longer, 24_117_296, "the 262,144-byte peak moved");
    assert!(
        longer > long,
        "the peak stopped growing with the message: {long} at 131,072 bytes \
         and {longer} at 262,144"
    );
}
